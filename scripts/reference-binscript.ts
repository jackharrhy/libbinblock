import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import type { ReferenceManifest } from './reference-manifest.js';

const repositoryRoot = resolve(fileURLToPath(new URL('..', import.meta.url)));
const manifestPath = resolve(repositoryRoot, 'reference-set/reference-manifest.json');
const outputPath = resolve(repositoryRoot, 'reference-set/reference-set.binscript');
const contractPath = resolve(repositoryRoot, 'reference-set/reference-conformance.tsv');

